"""Locator map for a viewer video: the Island of Newfoundland with a pin at the place it was taken.

Projects the Natural Earth province outlines (Web Mercator) into the card's map box and writes map.js
(land paths + pin/reference town positions) for index.html.

  python build.py [data/ne/adm1.geojson]
"""
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
W, H = 600, 520                                  # map box in CSS px (1080-wide frame)
LON = (-55.5, -52.1)                             # west/east edges; height follows from the Mercator scale
LAT_C = 48.3                                     # vertical centre
PIN = ("Bonavista", 48.649, -53.114)
REF = [("Gander", 48.954, -54.609), ("Clarenville", 48.164, -53.965), ("Trinity", 48.369, -53.358)]
PROV = ("Newfoundland and Labrador", "Québec", "Nova Scotia", "Prince Edward Island", "New Brunswick")


def merc(lat):
    return math.log(math.tan(math.pi / 4 + math.radians(lat) / 2))


def main(ne_path=os.path.join(HERE, "..", "..", "data", "ne", "adm1.geojson")):
    k = W / math.radians(LON[1] - LON[0])
    y0 = merc(LAT_C)
    proj = lambda lat, lon: (k * math.radians(lon - LON[0]), H / 2 - k * (merc(lat) - y0))
    paths = []
    with open(ne_path) as f:
        for ft in json.load(f)["features"]:
            if ft["properties"].get("name") not in PROV:
                continue
            g = ft["geometry"]
            for poly in g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]:
                pts = [proj(lat, lon) for lon, lat in poly[0]]
                xs, ys = [p[0] for p in pts], [p[1] for p in pts]
                if max(xs) < -20 or min(xs) > W + 20 or max(ys) < -20 or min(ys) > H + 20:
                    continue
                d, last = [], None
                for x, y in pts:                                   # drop points closer than 0.6 px
                    if last and abs(x - last[0]) + abs(y - last[1]) < 0.6:
                        continue
                    d.append(f"{x:.1f},{y:.1f}")
                    last = (x, y)
                if len(d) > 2:
                    paths.append("M" + "L".join(d) + "Z")
    data = {"w": W, "h": H, "land": paths,
            "pin": {"name": PIN[0], "xy": [round(v, 1) for v in proj(*PIN[1:])]},
            "ref": [{"name": n, "xy": [round(v, 1) for v in proj(la, lo)]} for n, la, lo in REF]}
    with open(os.path.join(HERE, "map.js"), "w") as f:
        f.write("// generated by build.py\nwindow.MAP = " + json.dumps(data) + ";\n")
    print(len(paths), "land paths; pin at", data["pin"]["xy"])


if __name__ == "__main__":
    main(*sys.argv[1:2])
