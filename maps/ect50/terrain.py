"""Ground for the ECT 50 scene: Mapbox Terrain-RGB heights + satellite imagery over the northeast Avalon, on one
Web-Mercator frame (tile-aligned). Writes terrain.js (window.TERRAIN: w, h, metres per cell, Int16 heights base64,
frame bounds) and texture.jpg.

  MAPBOX_ACCESS_TOKEN=... python3 terrain.py
"""
import base64
import io
import json
import math
import os
import urllib.error

import numpy as np
from matplotlib.image import imread
from PIL import Image
from scipy.ndimage import gaussian_filter, zoom

import fetch

HERE = os.path.dirname(os.path.abspath(__file__))
BOUNDS = dict(lat=(47.548, 47.806), lon=(-52.835, -52.585))     # route + margin, more sea to the east
ZT, ZS = 13, 14          # terrain / satellite tile zooms (satellite fetched @2x, so 4x the terrain detail)
CELL = 3                 # terrain pixels per mesh cell (~39 m)


def tile_xy(lat, lon, z):
    n = 2 ** z
    return (lon + 180) / 360 * n, (1 - math.log(math.tan(math.pi / 4 + math.radians(lat) / 2)) / math.pi) / 2 * n


def mosaic(z, url, tile_px, decode):
    x0, y0 = tile_xy(BOUNDS["lat"][1], BOUNDS["lon"][0], z)
    x1, y1 = tile_xy(BOUNDS["lat"][0], BOUNDS["lon"][1], z)
    tx0, ty0, tx1, ty1 = int(x0), int(y0), int(x1), int(y1)
    out = None
    for ty in range(ty0, ty1 + 1):
        for tx in range(tx0, tx1 + 1):
            try:
                img = decode(fetch.get(url.format(z=z, x=tx, y=ty)))
            except urllib.error.HTTPError:
                img = None
            if out is None:
                ch = 3
                out = np.zeros(((ty1 - ty0 + 1) * tile_px, (tx1 - tx0 + 1) * tile_px, ch), np.float32)
            if img is not None:
                out[(ty - ty0) * tile_px:(ty - ty0 + 1) * tile_px, (tx - tx0) * tile_px:(tx - tx0 + 1) * tile_px] = img[..., :3]
    # crop to the exact bounds (fractional tile coords -> pixels)
    c0, r0 = int((x0 - tx0) * tile_px), int((y0 - ty0) * tile_px)
    c1, r1 = int((x1 - tx0) * tile_px), int((y1 - ty0) * tile_px)
    return out[r0:r1, c0:c1], (tx0 + c0 / tile_px, ty0 + r0 / tile_px, tx0 + c1 / tile_px, ty0 + r1 / tile_px)


def main():
    tok = os.environ["MAPBOX_ACCESS_TOKEN"]
    rgb, _ = mosaic(ZT, "https://api.mapbox.com/v4/mapbox.terrain-rgb/{z}/{x}/{y}.pngraw?access_token=" + tok, 256,
                    lambda b: imread(io.BytesIO(b), format="png") * 255)
    h = -10000 + (rgb[..., 0] * 65536 + rgb[..., 1] * 256 + rgb[..., 2]) * 0.1
    h = np.clip(h, 0, None)
    h = gaussian_filter(h, 0.6)
    hs = h[: h.shape[0] // CELL * CELL, : h.shape[1] // CELL * CELL]
    hs = hs.reshape(hs.shape[0] // CELL, CELL, hs.shape[1] // CELL, CELL).mean((1, 3))
    lat_mid = sum(BOUNDS["lat"]) / 2
    m_per_cell = 40075016.686 * math.cos(math.radians(lat_mid)) / (256 * 2 ** ZT) * CELL
    sat, _ = mosaic(ZS, "https://api.mapbox.com/v4/mapbox.satellite/{z}/{x}/{y}@2x.jpg90?access_token=" + tok, 512,
                    lambda b: np.asarray(Image.open(io.BytesIO(b)).convert("RGB"), np.float32))
    img = Image.fromarray(np.clip(sat, 0, 255).astype(np.uint8))
    k = 4096 / max(img.size)                                     # WebGL-safe texture size
    if k < 1:
        img = img.resize((round(img.size[0] * k), round(img.size[1] * k)), Image.LANCZOS)
    img.save(os.path.join(HERE, "texture.jpg"), quality=90)
    sea = sat[zoom((h <= 0.5).astype(float), (sat.shape[0] / h.shape[0], sat.shape[1] / h.shape[1]), order=0)[:sat.shape[0], :sat.shape[1]] > 0.5]
    sea_rgb = [int(v) for v in np.median(sea, 0)] if len(sea) else [20, 40, 58]
    out = {"w": hs.shape[1], "h": hs.shape[0], "m_per_cell": m_per_cell, "bounds": BOUNDS, "sea": sea_rgb,
           "data": base64.b64encode(np.round(hs).astype("<i2").tobytes()).decode()}
    with open(os.path.join(HERE, "terrain.js"), "w") as f:
        f.write("// generated by terrain.py\nwindow.TERRAIN = " + json.dumps(out) + ";\n")
    print("terrain", hs.shape, "max", int(hs.max()), "m  cell", round(m_per_cell, 1), "m  texture", img.size, "sea", sea_rgb)


if __name__ == "__main__":
    main()
