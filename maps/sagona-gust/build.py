"""Sagona Island peak-gust hero map: Mapbox satellite basemaps for the 16:9 and 4:5 frames, plus the pixel
positions of the station and nearby towns. Writes map-{tv,social}.jpg and data.js (window.SG).

  MAPBOX_ACCESS_TOKEN=... python3 build.py
"""
import io
import json
import math
import os
import urllib.request

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
FRAMES = {"tv": dict(w=1920, h=1080, lon0=-56.05, lat0=47.33, zoom=8.75),
          "social": dict(w=1080, h=960, lon0=-55.62, lat0=47.33, zoom=8.30)}
STATION = ("Sagona Island", 47.367, -55.795)
TOWNS = {"Harbour Breton": (47.483, -55.797), "St. Alban's": (47.874, -55.843), "Grand Bank": (47.100, -55.765),
         "Fortune": (47.073, -55.826), "Marystown": (47.166, -55.148), "Burgeo": (47.617, -57.621),
         "Saint-Pierre": (46.778, -56.177)}


def world(lat, lon, z):
    s = 512 * 2 ** z
    return (lon + 180) / 360 * s, (1 - math.log(math.tan(math.pi / 4 + math.radians(lat) / 2)) / math.pi) / 2 * s


def main():
    tok = os.environ["MAPBOX_ACCESS_TOKEN"]
    data = {}
    for name, fr in FRAMES.items():
        url = (f"https://api.mapbox.com/styles/v1/mapbox/satellite-v9/static/{fr['lon0']},{fr['lat0']},{fr['zoom'] - 1:.3f},0/"
               f"{fr['w'] // 2}x{fr['h'] // 2}@2x?attribution=false&logo=false&access_token={tok}")
        with urllib.request.urlopen(url, timeout=90) as r:
            Image.open(io.BytesIO(r.read())).convert("RGB").resize((fr["w"], fr["h"]), Image.LANCZOS).save(
                os.path.join(HERE, f"map-{name}.jpg"), quality=90)
        cx, cy = world(fr["lat0"], fr["lon0"], fr["zoom"])
        proj = lambda la, lo: [round(world(la, lo, fr["zoom"])[0] - cx + fr["w"] / 2, 1), round(world(la, lo, fr["zoom"])[1] - cy + fr["h"] / 2, 1)]
        data[name] = {"station": proj(*STATION[1:]), "towns": {n: proj(*ll) for n, ll in TOWNS.items()}}
    with open(os.path.join(HERE, "data.js"), "w") as f:
        f.write("// generated by build.py\nwindow.SG = " + json.dumps(data) + ";\n")
    print(json.dumps(data))


if __name__ == "__main__":
    main()
