"""Wind direction at the time of the peak gust, at a spread of points, for arrows on the peak-gust map.

For each point: find the hour with the highest RDPS 10 m gust in the window, read the 10 m wind direction
at that hour, and write {x, y, from_deg, gust} in the view's pixel frame to peakdir{suffix}.js.

  python3 peakdir.py [view] [start] [end] [run]
"""
import json
import os
import re
import sys
from datetime import datetime, timedelta

import numpy as np

import build

POINTS = {   # spread over the Island, on land
    "Northern Peninsula north": (51.15, -55.95), "Northern Peninsula mid": (50.55, -56.95),
    "Gros Morne": (49.55, -57.55), "Baie Verte": (49.75, -56.25), "Notre Dame Bay": (49.35, -55.30),
    "Gander area": (48.90, -54.35), "Bonavista Peninsula": (48.55, -53.55), "Central": (48.55, -56.20),
"South coast": (47.75, -57.25), "Burin Peninsula": (47.35, -55.35),
    "Avalon": (47.35, -53.15), "Southwest interior": (48.45, -58.05),
}


def main(view="wind-island", start="2026-10-17T00:00:00Z", end="2026-10-18T00:00:00Z", run=None):
    v = build.VIEWS[view]
    build.LON0, build.LAT0 = v["center"]
    build.ZOOM = v["zoom"]
    build.W, build.H = v.get("size", (1920, 1080))
    build.BOX, build.RES = dict(lat=(46.0, 52.5), lon=(-60.5, -52.0)), 0.1
    if not run:
        caps = build.fetch(f"{build.GEOMET}?service=WMS&version=1.3.0&request=GetCapabilities&layer=RDPS_10km_WindGust_10m").decode()
        run = re.search(r'<Dimension name="reference_time"[^>]*default="([^"]+)"', caps).group(1)
    t, t1 = (datetime.fromisoformat(x.replace("Z", "+00:00")) for x in (start, end))
    t += timedelta(hours=1)
    best = {n: (-1, None, None) for n in POINTS}            # gust m/s, direction, time
    while t <= t1:
        ts = t.strftime("%Y-%m-%dT%H:%M:%SZ")
        g, h = build.grid("RDPS_10km_WindGust_10m", run, ts)
        d, _ = build.grid("RDPS_10km_WindDir_10m", run, ts)
        top = h["yllcorner"] + h["nrows"] * h["dy"]
        for n, (la, lo) in POINTS.items():
            r, c = int((top - la) / h["dy"]), int((lo - h["xllcorner"]) / h["dx"])
            if g[r, c] > best[n][0]:
                best[n] = (float(g[r, c]), float(d[r, c]), t.astimezone(build.NDT).strftime("%a %-I %p"))
        t += timedelta(hours=1)
    out = [{"name": n, "xy": build.px(*POINTS[n]), "from": round(b[1]), "gust": round(b[0] * 3.6), "at": b[2]}
           for n, b in best.items()]
    for o in out:
        print(f"{o['name']:26} {o['gust']:4} km/h from {o['from']:3} deg at {o['at']}")
    with open(os.path.join(build.HERE, f"peakdir{v['suffix']}.js"), "w") as f:
        f.write("// generated by peakdir.py\nwindow.PEAKDIR = " + json.dumps({"run": run, "points": out}) + ";\n")


if __name__ == "__main__":
    main(*sys.argv[1:5])
