"""Track of the storm's low centre from RDPS mean sea level pressure, for the combined rain/snow map.

Every 3 h, take the pressure minimum within ~3 deg of the previous position (the first step searches the
FIRST box, southwest of the province, so an older low elsewhere isn't picked up), and write the positions in the chosen view's pixel frame to track{suffix}.js.

  python3 track.py [view] [start] [end] [run]      e.g. storm-social 2026-10-16T12:00:00Z 2026-10-18T06:00:00Z
"""
import json
import os
import re
import sys
from datetime import datetime, timedelta

import numpy as np
from scipy.ndimage import gaussian_filter

import build

BOX = dict(lat=(42.0, 62.0), lon=(-72.0, -46.0))
FIRST = dict(lat=(43.5, 49.0), lon=(-72.0, -62.0))       # where the storm low starts (Maine/Gulf), not the old Labrador Sea low


def main(view="storm-social", start="2026-10-16T12:00:00Z", end="2026-10-18T06:00:00Z", run=None):
    v = build.VIEWS[view]
    build.LON0, build.LAT0 = v["center"]
    build.ZOOM = v["zoom"]
    build.W, build.H = v.get("size", (1920, 1080))
    build.BOX, build.RES = BOX, 0.1
    if not run:
        caps = build.fetch(f"{build.GEOMET}?service=WMS&version=1.3.0&request=GetCapabilities&layer=RDPS_10km_Pressure_MSL").decode()
        run = re.search(r'<Dimension name="reference_time"[^>]*default="([^"]+)"', caps).group(1)
    t, t1 = (datetime.fromisoformat(x.replace("Z", "+00:00")) for x in (start, end))
    pts, prev = [], None
    while t <= t1:
        a, h = build.grid("RDPS_10km_Pressure_MSL", run, t.strftime("%Y-%m-%dT%H:%M:%SZ"))
        a = gaussian_filter(a, 1.5)
        lats = h["yllcorner"] + (h["nrows"] - 0.5 - np.arange(a.shape[0])) * h["dy"]
        lons = h["xllcorner"] + (np.arange(a.shape[1]) + 0.5) * h["dx"]
        LO, LA = np.meshgrid(lons, lats)
        if not prev:
            a = np.where((LA >= FIRST["lat"][0]) & (LA <= FIRST["lat"][1]) & (LO >= FIRST["lon"][0]) & (LO <= FIRST["lon"][1]), a, np.inf)
        else:
            a = np.where((LA - prev[0]) ** 2 + ((LO - prev[1]) * 0.6) ** 2 < 3 ** 2, a, np.inf)
        r, c = np.unravel_index(np.argmin(a), a.shape)
        p = a[r, c] / (100 if a[r, c] > 2000 else 1)          # Pa -> hPa if needed
        prev = (float(LA[r, c]), float(LO[r, c]))
        local = t.astimezone(build.NDT)
        pts.append({"t": local.strftime("%a %-I %p"), "lat": round(prev[0], 2), "lon": round(prev[1], 2),
                    "hpa": round(float(p)), "xy": build.px(*prev)})
        print(local.strftime("%a %H:%M"), prev, round(float(p)))
        t += timedelta(hours=3)
    with open(os.path.join(build.HERE, f"track{v['suffix']}.js"), "w") as f:
        f.write("// generated by track.py\nwindow.TRACK = " + json.dumps({"run": run, "points": pts}) + ";\n")


if __name__ == "__main__":
    main(*sys.argv[1:5])
