"""Wind streamlines at one time (around the peak) for the peak-gust map, drawn on land only.

RDPS 10 m wind speed and direction -> u/v on the view's pixel grid -> matplotlib streamplot, rendered to a
transparent stream{suffix}.png the page lays over the shading (?stream). Line width grows with wind speed.

  python3 streamlines.py [view] [valid] [ne_admin1.geojson] [run]     e.g. wind-island 2026-10-17T15:00:00Z
"""
import json
import os
import re
import sys
from datetime import datetime

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
from scipy.ndimage import gaussian_filter, map_coordinates  # noqa: E402

import build  # noqa: E402


def main(view="wind-island", valid="2026-10-17T15:00:00Z", ne_path=None, run=None):
    v = build.VIEWS[view]
    build.LON0, build.LAT0 = v["center"]
    build.ZOOM = v["zoom"]
    build.W, build.H = v.get("size", (1920, 1080))
    build.BOX, build.RES = dict(lat=(45.5, 53.0), lon=(-61.5, -51.0)), 0.1
    if not run:
        caps = build.fetch(f"{build.GEOMET}?service=WMS&version=1.3.0&request=GetCapabilities&layer=RDPS_10km_WindSpeed_10m").decode()
        run = re.search(r'<Dimension name="reference_time"[^>]*default="([^"]+)"', caps).group(1)
    spd, h = build.grid("RDPS_10km_WindSpeed_10m", run, valid)
    dr, _ = build.grid("RDPS_10km_WindDir_10m", run, valid)
    LON, LAT = build.frame_lonlat()
    top = h["yllcorner"] + h["nrows"] * h["dy"]
    rows, cols = (top - LAT) / h["dy"] - .5, (LON - h["xllcorner"]) / h["dx"] - .5
    th = np.radians(dr)                                  # direction the wind blows FROM, degrees from north
    u = -spd * np.sin(th)
    vv = -spd * np.cos(th)                                # +v = northward
    U = map_coordinates(gaussian_filter(u, 1), [rows, cols], order=1)
    V = -map_coordinates(gaussian_filter(vv, 1), [rows, cols], order=1)   # screen y points down
    S = np.hypot(U, V) * 3.6
    land = build.land_mask()
    if ne_path:
        land = land * build.nl_mask(ne_path, island_only=True)
    # integrate over the whole field (masking first stops most lines at the coast), clip to land afterwards
    step = 8
    ys, xs = np.arange(0, build.H, step), np.arange(0, build.W, step)
    Us, Vs, Ss = U[::step, ::step], V[::step, ::step], S[::step, ::step]
    fig = plt.figure(figsize=(build.W / 100, build.H / 100), dpi=100)
    ax = fig.add_axes([0, 0, 1, 1])
    ax.set_xlim(0, build.W); ax.set_ylim(build.H, 0); ax.axis("off")
    lw = 1.6 + 2.4 * np.clip((Ss - 30) / 60, 0, 1)
    seeds = np.array([[x, y] for y in range(30, build.H, 70) for x in range(30, build.W, 70)
                      if land[min(y, build.H - 1), min(x, build.W - 1)] > 0.5], float)
    for col, wmul, asz in (("white", 2.4, 2.0), ("#10222B", 1.0, 1.5)):       # white casing under a dark line
        ax.streamplot(xs, ys, Us, Vs, start_points=seeds, color=col, linewidth=lw * wmul, arrowsize=asz,
                      arrowstyle="-|>", integration_direction="both", maxlength=0.35, density=3,
                      broken_streamlines=True)
    fig.patch.set_alpha(0); ax.patch.set_alpha(0)
    fig.canvas.draw()
    img = np.asarray(fig.canvas.buffer_rgba()).astype(float) / 255
    plt.close(fig)
    img[..., 3] *= np.clip(land, 0, 1) * 0.85
    out = os.path.join(build.HERE, f"stream{v['suffix']}.png")
    plt.imsave(out, img)
    t = datetime.fromisoformat(valid.replace("Z", "+00:00")).astimezone(build.NDT)
    with open(os.path.join(build.HERE, f"stream{v['suffix']}.js"), "w") as f:
        f.write("// generated by streamlines.py\nwindow.STREAM = " + json.dumps({"run": run, "valid": t.strftime("%a %-I:%M %p NDT")}) + ";\n")
    print("wrote", out, "valid", t)


if __name__ == "__main__":
    main(*sys.argv[1:5])
