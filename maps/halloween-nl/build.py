"""Halloween trick-or-treat forecast for NL: TWC town forecasts at 7 PM local on Saturday Oct 31 (icon + temp),
GDPS 2 m temperature at 21Z (6:30 PM NDT) shaded on NL land in a Halloween palette, neighbouring land as
silhouettes. Reuses the nl-temps helpers (frame, land mask, coast path). Writes shade.png and data.js (window.HW).

  MAPBOX_ACCESS_TOKEN=... TWC_API_KEY=... python3 build.py data/ne/adm1.geojson
"""
import importlib.util
import json
import os
import sys
import urllib.request

import numpy as np
from matplotlib.image import imsave
from scipy.ndimage import gaussian_filter, map_coordinates

HERE = os.path.dirname(os.path.abspath(__file__))
_spec = importlib.util.spec_from_file_location("nb", os.path.join(HERE, "..", "nl-temps", "build.py"))
nb = importlib.util.module_from_spec(_spec); _spec.loader.exec_module(nb)

DATE, GRID_HOURS = "2026-10-31", (21,)                    # GDPS 21Z = 6:30 PM NDT / 6 PM ADT
WANT = {"-0230": ("T18:30", "T19:30"), "-0300": ("T19:00",)}   # 7 PM local: Island averages the half hours
PAL = {-10: "#1F0B3A", -8: "#2C1252", -6: "#3E1A6C", -4: "#532487", -2: "#6B2F9E", 0: "#8E3B8E",
       2: "#B4463F", 4: "#D9581E", 6: "#F07A1A", 8: "#F9A03A", 10: "#FFC766"}
NEIGHBOURS = ("Québec", "Nova Scotia", "New Brunswick", "Prince Edward Island")


def twc_7pm(towns):
    out = {}
    for n, t in towns.items():
        d = json.load(urllib.request.urlopen(
            f"https://api.weather.com/v3/wx/forecast/hourly/15day?geocode={t[0]},{t[1]}&format=json&units=m"
            f"&language=en-CA&apiKey={os.environ['TWC_API_KEY']}", timeout=60))
        idx = [i for i, v in enumerate(d["validTimeLocal"]) if v.startswith(DATE) and
               any(v[10:16] == w and v.endswith(z) for z, ws in WANT.items() for w in ws)]
        i = idx[-1]                                          # icon/wind/phrase from the later slot
        code = d["iconCode"][i]
        out[n] = {"temp": round(sum(d["temperature"][j] for j in idx) / len(idx)),
                  "feels": round(sum(d["temperatureFeelsLike"][j] for j in idx) / len(idx)),
                  "icon": nb.NIGHT.get(code) or nb.ICONS.get(code, "cloud"), "code": code,
                  "phrase": d["wxPhraseLong"][i], "pop": max(d["precipChance"][j] for j in idx),
                  "wind": f"{d['windDirectionCardinal'][i]} {d['windSpeed'][i]}"}
        print(f"{n:24s} {out[n]['temp']:>3} feels {out[n]['feels']:>3}  {out[n]['icon']:11s} {out[n]['phrase']}  pop {out[n]['pop']}  {out[n]['wind']}")
    return out


def main(ne_path):
    r = nb.REGIONS["nl"]
    (nb.LON0, nb.LAT0), nb.ZOOM, nb.TOWNS, nb.BOX = r["center"], r["zoom"], r["towns"], r["box"]
    nb.MODEL = "GDPS_15km_AirTemp_2m"
    towns = twc_7pm(nb.TOWNS)
    proj = nb.projector()
    lons, lats, t = nb.hrdps_daytime_max(DATE, GRID_HOURS)
    with open(ne_path) as f:
        feats = {ft["properties"].get("name"): ft["geometry"] for ft in json.load(f)["features"]}
    rings = [p[0] for p in feats["Newfoundland and Labrador"]["coordinates"] if len(p[0]) > 20]
    scale = 2
    land, LON, LAT = nb.land_mask(scale)
    nl_land = nb.in_rings(rings, LON, LAT, land)
    ti = map_coordinates(gaussian_filter(t, 1.2), [(lats[0] - LAT) / (lats[0] - lats[1]), (LON - lons[0]) / (lons[1] - lons[0])], order=1)
    band = np.clip((np.floor(ti / 2) * 2).astype(int), -10, 10)
    rgba = np.zeros(band.shape + (4,))
    for b, c in PAL.items():
        rgba[band == b, :3] = [int(c[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    rgba[..., 3] = nl_land * 0.92
    imsave(os.path.join(HERE, "shade.png"), rgba)
    other = []                                                 # neighbouring land, as dark silhouettes
    for nm in NEIGHBOURS:
        g = feats[nm]
        other += [p[0] for p in (g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]])]
    data = {"towns": {n: {**towns[n], "xy": [round(v) for v in proj(*nb.TOWNS[n][:2])],
                          "card": [round(proj(*nb.TOWNS[n][:2])[0] + nb.TOWNS[n][2]), round(proj(*nb.TOWNS[n][:2])[1] + nb.TOWNS[n][3])]}
                      for n in nb.TOWNS},
            "pal": {str(k): v for k, v in PAL.items()}, "bands_used": sorted(set(band[nl_land].tolist())),
            "coast": nb.coast_path(nl_land, scale), "other": nb.svg_path(other, proj, 1.5), "w": nb.W, "h": nb.H}
    with open(os.path.join(HERE, "data.js"), "w") as f:
        f.write("// generated by build.py\nwindow.HW = " + json.dumps(data) + ";\n")
    print("GDPS 21Z over grid:", round(float(t.min()), 1), "to", round(float(t.max()), 1), "bands", data["bands_used"])


if __name__ == "__main__":
    main(*sys.argv[1:2])
