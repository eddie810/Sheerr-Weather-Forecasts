"""Overnight planner for one airport/town: hourly temperature, feels-like and cloud cover.

  TWC_API_KEY=... python3 build.py [lat,lon] [hours]
  default: YYT (St. John's airport), the next 13 hours
"""
import json
import os
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))


def main(geo="47.619,-52.752", hours="13"):
    url = (f"https://api.weather.com/v3/wx/forecast/hourly/2day?geocode={geo}&format=json&units=m"
           f"&language=en-CA&apiKey={os.environ['TWC_API_KEY']}")
    with urllib.request.urlopen(url, timeout=60) as r:
        d = json.load(r)
    keys = ["validTimeLocal", "temperature", "temperatureFeelsLike", "cloudCover", "precipChance", "iconCode",
            "wxPhraseLong", "windSpeed", "windDirectionCardinal", "dayOrNight"]
    rows = [dict(zip(keys, v)) for v in zip(*(d[k] for k in keys))][:int(hours)]
    with open(os.path.join(HERE, "data.js"), "w") as f:
        f.write("// generated by build.py\nwindow.HOURS = " + json.dumps(rows) + ";\n")
    for r in rows:
        print(r["validTimeLocal"][5:16], r["temperature"], r["temperatureFeelsLike"], r["cloudCover"], r["precipChance"], r["wxPhraseLong"])


if __name__ == "__main__":
    main(*sys.argv[1:3])
