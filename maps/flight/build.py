"""Flight forecast graphic: YYT -> MCO on a given day.

Pulls TWC hourly forecasts for both airports, summarises morning / afternoon / evening
at the departure airport and the afternoon at the arrival airport, and fetches a Mapbox
basemap framed on the great-circle route.

  MAPBOX_ACCESS_TOKEN=... TWC_API_KEY=... python3 build.py 2026-10-12
"""
import json
import math
import os
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
W, H = 1080, 830
LON0, LAT0, ZOOM = -66.8, 38.6, 4.18
AIRPORTS = {"YYT": ("St. John's", 47.619, -52.752), "MCO": ("Orlando", 28.429, -81.309)}
ICONS = {}
for codes, name in [((32, 34, 36, 31, 33), "sun"), ((30, 29), "partly"), ((28, 27), "mostly"), ((26, 44), "cloud"),
                    ((39, 45), "showers"), ((9, 11, 12, 40), "rain"), ((23, 24, 25), "wind"),
                    ((13, 14, 15, 16, 41, 42, 43, 46, 5, 6, 7, 8, 10, 18, 35), "snow"), ((3, 4, 37, 38, 47), "thunder"),
                    ((19, 20, 21, 22), "fog")]:
    for c in codes:
        ICONS[c] = name


def get(url):
    with urllib.request.urlopen(url, timeout=60) as r:
        return r.read()


def px(lat, lon):
    s = 512 * 2 ** ZOOM
    f = lambda la, lo: ((lo + 180) / 360 * s, (1 - math.log(math.tan(math.pi / 4 + math.radians(la) / 2)) / math.pi) / 2 * s)
    (x, y), (cx, cy) = f(lat, lon), f(LAT0, LON0)
    return [round(x - cx + W / 2, 1), round(y - cy + H / 2, 1)]


def great_circle(a, b, n=80):
    la1, lo1, la2, lo2 = map(math.radians, (a[0], a[1], b[0], b[1]))
    d = 2 * math.asin(math.sqrt(math.sin((la2 - la1) / 2) ** 2 + math.cos(la1) * math.cos(la2) * math.sin((lo2 - lo1) / 2) ** 2))
    pts = []
    for i in range(n + 1):
        f = i / n
        A, B = math.sin((1 - f) * d) / math.sin(d), math.sin(f * d) / math.sin(d)
        x = A * math.cos(la1) * math.cos(lo1) + B * math.cos(la2) * math.cos(lo2)
        y = A * math.cos(la1) * math.sin(lo1) + B * math.cos(la2) * math.sin(lo2)
        z = A * math.sin(la1) + B * math.sin(la2)
        pts.append(px(math.degrees(math.atan2(z, math.hypot(x, y))), math.degrees(math.atan2(y, x))))
    return pts, d * 6371


def hourly(lat, lon, day):
    d = json.loads(get(f"https://api.weather.com/v3/wx/forecast/hourly/15day?geocode={lat},{lon}&format=json&units=m"
                       f"&language=en-CA&apiKey={os.environ['TWC_API_KEY']}"))
    keys = ("validTimeLocal", "temperature", "iconCode", "wxPhraseLong", "precipChance", "windSpeed", "windGust",
            "windDirectionCardinal", "visibility")
    return [dict(zip(keys, row)) for row in zip(*(d[k] for k in keys)) if row[0].startswith(day)]


def block(rows, h0, h1, label):
    r = [x for x in rows if h0 <= int(x["validTimeLocal"][11:13]) < h1]
    worst = max(r, key=lambda x: (x["precipChance"], x["windGust"] or 0))
    gust = max((x["windGust"] or x["windSpeed"]) for x in r)
    return {"label": label, "hi": max(x["temperature"] for x in r), "lo": min(x["temperature"] for x in r),
            "icon": ICONS.get(worst["iconCode"], "cloud"), "phrase": worst["wxPhraseLong"],
            "pop": max(x["precipChance"] for x in r), "gust": gust,
            "wind": max(r, key=lambda x: x["windSpeed"])["windDirectionCardinal"],
            "vis": min(x["visibility"] for x in r)}


def main(day):
    yyt, mco = (hourly(*AIRPORTS[k][1:], day) for k in ("YYT", "MCO"))
    route, km = great_circle(AIRPORTS["YYT"][1:], AIRPORTS["MCO"][1:])
    data = {
        "day": day, "km": round(km),
        "route": route, "airports": {k: {"name": v[0], "xy": px(*v[1:])} for k, v in AIRPORTS.items()},
        "yyt": [block(yyt, 6, 11, "Morning"), block(yyt, 11, 17, "Afternoon"), block(yyt, 17, 23, "Evening")],
        "mco": block(mco, 11, 19, "Afternoon"),
    }
    with open(os.path.join(HERE, "data.js"), "w") as f:
        f.write("// generated by build.py\nwindow.FLIGHT = " + json.dumps(data) + ";\n")
    with open(os.path.join(HERE, "map.png"), "wb") as f:
        f.write(get(f"https://api.mapbox.com/styles/v1/mapbox/light-v11/static/{LON0},{LAT0},{ZOOM},0/{W}x{H}@2x"
                    f"?attribution=false&logo=false&access_token={os.environ['MAPBOX_ACCESS_TOKEN']}"))
    print(json.dumps({k: data[k] for k in ("km", "yyt", "mco", "airports")}, indent=1))


if __name__ == "__main__":
    main(sys.argv[1])
