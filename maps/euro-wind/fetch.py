"""ECMWF IFS (open data, 0.25 deg) wind gusts, MSLP and 10 m wind over the North Atlantic, every 3 h for 5 days.

Writes euro.bin (Float32 [step][lat][lon][4] = gust km/h, MSLP hPa, u, v m/s; rows south -> north) and euro.js
(window.WAVES-style metadata as window.EURO: grid, times, H/L tracks, max gust per step).

  python3 fetch.py [YYYYMMDDHH run] [first_step] [last_step]      (default: latest 00Z/12Z run, next 5 days)
"""
import importlib.util
import json
import os
import subprocess
import sys
import tempfile
import time
from datetime import datetime, timedelta, timezone

import numpy as np
import pygrib

HERE = os.path.dirname(os.path.abspath(__file__))
W, E, S, N = -88.0, -2.0, 22.0, 68.0
BASE = "https://data.ecmwf.int/forecasts/{d}/{h:02d}z/ifs/0p25/oper/{d}{h:02d}0000-{s}h-oper-fc"
PARAMS = ("10fg", "msl", "10u", "10v")
_spec = importlib.util.spec_from_file_location("wavefetch", os.path.join(HERE, "..", "waves-3d", "fetch.py"))
_wf = importlib.util.module_from_spec(_spec); _spec.loader.exec_module(_wf)
tracks = _wf.tracks                                   # same H/L finder + linker as the wave loop


def curl(url, rng=None):
    for k in range(5):
        cmd = ["curl", "-sf", "-A", "Mozilla/5.0 sheerr-weather"] + (["-r", rng] if rng else []) + [url]
        r = subprocess.run(cmd, capture_output=True)
        if r.returncode == 0 and r.stdout:
            return r.stdout
        time.sleep(2 ** (k + 1))
    raise OSError("download failed: " + url)


def latest_run():
    now = datetime.now(timezone.utc)
    for back in range(0, 72, 12):
        t = now - timedelta(hours=back)
        run = t.replace(hour=t.hour // 12 * 12, minute=0, second=0, microsecond=0)
        url = BASE.format(d=run.strftime("%Y%m%d"), h=run.hour, s=144) + ".index"
        if subprocess.run(["curl", "-sf", "-o", "/dev/null", url]).returncode == 0:
            return run
    raise RuntimeError("no complete ECMWF run found")


def main(run=None, s0=None, s1=None):
    run = datetime.strptime(run, "%Y%m%d%H").replace(tzinfo=timezone.utc) if run else latest_run()
    now = datetime.now(timezone.utc)
    s0 = int(s0) if s0 else max(0, int((now - run).total_seconds() // 3600) // 3 * 3)
    s1 = int(s1) if s1 else s0 + 120
    tmp = tempfile.mkdtemp()
    steps, press, times, gmax = [], [], [], []
    for s in range(s0, s1 + 1, 3):
        base = BASE.format(d=run.strftime("%Y%m%d"), h=run.hour, s=s)
        idx = [json.loads(l) for l in curl(base + ".index").decode().splitlines()]
        f = os.path.join(tmp, "x.grb")
        with open(f, "wb") as out:
            for p in PARAMS:
                names = ("10fg", "10fg3", "10fg6") if p == "10fg" else (p,)   # the gust field is renamed past +90 h
                e = next(e for e in idx if e["param"] in names and e.get("levtype") == "sfc")
                out.write(curl(base + ".grib2", f"{e['_offset']}-{e['_offset'] + e['_length'] - 1}"))
        msgs = list(pygrib.open(f))                                 # written in PARAMS order: gust, msl, 10u, 10v
        g = {"gust": msgs[0], "msl": msgs[1], "10u": msgs[2], "10v": msgs[3]}
        lat, lon = g["msl"].latlons()
        lat1, lon1 = lat[:, 0], ((lon[0] + 180) % 360) - 180
        order = np.argsort(lon1)                                   # 0..360 -> -180..180, sorted
        lon1 = lon1[order]
        ci = np.where((lon1 >= W) & (lon1 <= E))[0]
        ri = np.where((lat1 >= S) & (lat1 <= N))[0][::-1]           # south -> north
        def crop(m):
            return m.values[:, order][ri][:, ci].astype("f8")
        gust, P, u, v = crop(g["gust"]) * 3.6, crop(g["msl"]) / 100, crop(g["10u"]), crop(g["10v"])
        steps.append(np.stack([gust, P, u, v], -1).astype("<f4"))
        press.append(P)
        times.append((run + timedelta(hours=s)).isoformat())
        gmax.append(float(gust.max()))
        print(f"+{s:3d}h  gust max {gust.max():5.0f} km/h  MSLP {P.min():6.1f}-{P.max():6.1f}", flush=True)
    lat, lon = lat1[ri], lon1[ci]
    np.stack(steps).tofile(os.path.join(HERE, "euro.bin"))
    sea = np.ones((len(lat), len(lon)), bool)                        # basemap.py wants a sea mask; lakes come from NE
    import base64
    meta = {"run": run.isoformat(), "times": times, "nx": len(lon), "ny": len(lat),
            "lon0": float(lon[0]), "lat0": float(lat[0]), "dlon": float(lon[1] - lon[0]), "dlat": float(lat[1] - lat[0]),
            "sea": base64.b64encode(np.packbits(sea.ravel()).tobytes()).decode(),
            "tracks": tracks(press, lat, lon, "L") + tracks(press, lat, lon, "H"), "gmax": gmax}
    with open(os.path.join(HERE, "euro.js"), "w") as f:
        f.write("// generated by fetch.py\nwindow.EURO = " + json.dumps(meta) + ";\n")
    # basemap.py reads waves.js for the frame: same metadata under that name
    with open(os.path.join(HERE, "waves.js"), "w") as f:
        f.write("// frame for basemap.py (copy of euro.js)\nwindow.WAVES = " + json.dumps(meta) + ";\n")
    print(len(steps), "steps", len(lat), "x", len(lon), len(meta["tracks"]), "H/L tracks")


if __name__ == "__main__":
    main(*sys.argv[1:4])
