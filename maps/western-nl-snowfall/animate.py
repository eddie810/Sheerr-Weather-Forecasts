"""Animate snowfall building up over the Long Range Mountains (tight view) from HRDPS.

Each frame is the HRDPS accumulated snow since the run started (liquid equivalent),
converted at SNOW_RATIO and weighted by elevation exactly like build.py, then contoured.
Ends at UNTIL (Monday evening) or the last hour the newest run reaches, whichever is first.

  MAPBOX_ACCESS_TOKEN=... python3 animate.py [until_iso]     then: node render-anim.js
"""
import json
import os
import re
import sys
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timedelta, timezone

import numpy as np
from scipy.ndimage import gaussian_filter

import build

HERE = build.HERE
UNTIL = "2026-10-13T00:00:00Z"            # Monday 9:30 PM NDT
NDT = timezone(timedelta(hours=-2, minutes=-30))
GEOMET = "https://geo.weather.gc.ca/geomet"


def fetch(url, tries=5):
    import time
    for n in range(tries):
        try:
            with urllib.request.urlopen(url, timeout=180) as r:
                return r.read()
        except OSError:
            if n == tries - 1:
                raise
            time.sleep(2 ** (n + 1))


def latest_run():
    caps = fetch(f"{GEOMET}?service=WMS&version=1.3.0&request=GetCapabilities&layer=HRDPS.CONTINENTAL_SN").decode()
    ref = re.search(r'<Dimension name="reference_time"[^>]*default="([^"]+)"', caps).group(1)
    last = re.search(r'<Dimension name="time"[^>]*>([^<]+)</Dimension>', caps).group(1).split("/")[1]
    return ref, datetime.fromisoformat(last.replace("Z", "+00:00"))


def sn_grid(run, valid, box):
    url = (f"{GEOMET}?service=WCS&version=2.0.1&request=GetCoverage&coverageId=HRDPS.CONTINENTAL_SN"
           f"&subsettingcrs=EPSG:4326&outputcrs=EPSG:4326&subset=lat({box['lat'][0]},{box['lat'][1]})"
           f"&subset=lon({box['lon'][0]},{box['lon'][1]})&resolution=lat(0.02)&resolution=lon(0.03)"
           f"&time={valid}&DIM_REFERENCE_TIME={run}&format=image/x-aaigrid")
    body = fetch(url).decode("latin1").split("filename=result.grd", 1)[1].split("--wcs")[0].strip().splitlines()
    hdr, i = {}, 0
    while re.match(r"^[a-zA-Z_]+\s", body[i]):
        k, v = body[i].split()[:2]
        hdr[k.lower()] = float(v)
        i += 1
    a = np.array(" ".join(body[i:]).split(), float).reshape(int(hdr["nrows"]), int(hdr["ncols"]))
    lons = hdr["xllcorner"] + hdr["dx"] * (np.arange(a.shape[1]) + 0.5)
    lats = (hdr["yllcorner"] + hdr["dy"] * (np.arange(a.shape[0]) + 0.5))[::-1]
    return lons, lats, np.clip(a, 0, None)


def main(until=UNTIL):
    v = build.VIEWS["tight"]
    (build.LON0, build.LAT0), build.ZOOM, build.TOWNS, build.PEAKS = v["center"], v["zoom"], v["towns"], v["peaks"]
    proj = build.projector()
    box = dict(lat=(48.3, 51.4), lon=(-59.6, -55.0))

    run, last = latest_run()
    start = datetime.fromisoformat(run.replace("Z", "+00:00"))
    end = min(datetime.fromisoformat(until.replace("Z", "+00:00")), last)
    times = []
    t = start + timedelta(hours=1)
    while t <= end:
        times.append(t)
        t += timedelta(hours=1)

    lons, lats, _ = sn_grid(run, times[0].strftime("%Y-%m-%dT%H:%M:%SZ"), box)
    ramp = np.clip((build.elevation_grid(lons, lats) - build.SNOW_FLOOR_M) / (build.SNOW_FULL_M - build.SNOW_FLOOR_M), 0, 1)

    def frame(t):
        _, _, mm = sn_grid(run, t.strftime("%Y-%m-%dT%H:%M:%SZ"), box)
        cm = gaussian_filter(mm, 1.0) * build.SNOW_RATIO / 10 * ramp
        bands, _ = build.contour_bands(lons, lats, cm, proj)
        return {"time": t.astimezone(NDT).strftime("%a %-I:%M %p"), "bands": bands, "max": round(float(cm.max()))}

    with ThreadPoolExecutor(3) as ex:
        frames = list(ex.map(frame, times))

    run_t = start.astimezone(NDT)
    data = {"frames": frames, "run": f"HRDPS {start:%HZ} run {start:%b %-d}",
            "from": run_t.strftime("%a %-I:%M %p"), "to": frames[-1]["time"], "ratio": build.SNOW_RATIO}
    with open(os.path.join(HERE, "frames-tight.js"), "w") as f:
        f.write("// generated by animate.py\nwindow.ANIM = " + json.dumps(data) + ";\n")
    print(len(frames), "frames", data["from"], "->", data["to"], "| max", frames[-1]["max"], "cm |", data["run"])


if __name__ == "__main__":
    main(*sys.argv[1:2])
