"""St. John's sunrise/sunset on the solstices under permanent standard time (NST, UTC-3:30) and permanent daylight
time (NDT, UTC-2:30). Writes data.js (window.WI).   python3 build.py   (needs astral)"""
import json
import os
from datetime import date, timedelta, timezone

from astral import LocationInfo
from astral.sun import sun

HERE = os.path.dirname(os.path.abspath(__file__))
OBS = LocationInfo("St. John's", "", "UTC", 47.561, -52.713).observer
DAYS = {"summer": date(2026, 6, 21), "winter": date(2026, 12, 21)}
ZONES = {"std": -3.5, "dst": -2.5}


def main():
    out = {}
    for k, d in DAYS.items():
        s = sun(OBS, date=d, tzinfo=timezone.utc)
        out[k] = {"len": round((s["sunset"] - s["sunrise"]).total_seconds() / 3600, 2)}
        for z, h in ZONES.items():
            tz = timezone(timedelta(hours=h))
            r, t = s["sunrise"].astimezone(tz), s["sunset"].astimezone(tz)
            out[k][z] = [r.hour + r.minute / 60, t.hour + t.minute / 60]
    with open(os.path.join(HERE, "data.js"), "w") as f:
        f.write("// generated by build.py\nwindow.WI = " + json.dumps(out) + ";\n")
    print(out)


if __name__ == "__main__":
    main()
