"""Build the Labrador City & Wabush alert graphic assets.

Pulls the live alert polygon from The Weather Company, renders the Mapbox
basemap with it, and projects the NL/Quebec boundaries (Natural Earth 10m
admin-1) into SVG paths for the main map and the locator inset.

  MAPBOX_ACCESS_TOKEN=... TWC_API_KEY=... python3 build.py ne_10m_admin_1_states_provinces.geojson
"""
import json
import math
import os
import sys
import urllib.parse
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
GEOCODE = "52.94,-66.91"
# Main map frame (CSS px; the PNG is fetched @2x). Taller than either layout
# shows: the page centre-crops it to fit the feed and story versions.
LON0, LAT0, ZOOM, W, H = -65.95, 52.93, 6.85, 1080, 720
# Locator inset frame
INSET = dict(lon0=-61.5, lat0=52.6, zoom=3.3, w=230, h=250)

TOWNS = {
    "Labrador City": (52.946, -66.911),
    "Wabush": (52.906, -66.872),
    "Fermont": (52.787, -67.086),
    "Churchill Falls": (53.528, -63.966),
}


def get_json(url):
    with urllib.request.urlopen(url) as r:
        return json.load(r)


def projector(lon0, lat0, zoom, w, h):
    s = 512 * 2 ** zoom / (2 * math.pi)
    mx = lambda lo: s * math.radians(lo)
    my = lambda la: s * math.log(math.tan(math.pi / 4 + math.radians(la) / 2))
    return lambda la, lo: (w / 2 + mx(lo) - mx(lon0), h / 2 - (my(la) - my(lat0)))


def rings(geom):
    polys = geom["coordinates"] if geom["type"] == "MultiPolygon" else [geom["coordinates"]]
    for poly in polys:
        for ring in poly:
            yield ring


def path(geom, proj, w, h, min_px=1.2, pad=400):
    """SVG path for a (Multi)Polygon, dropping rings that are off-frame or tiny."""
    out = []
    for ring in rings(geom):
        pts = [proj(la, lo) for lo, la in ring]
        xs, ys = [p[0] for p in pts], [p[1] for p in pts]
        if max(xs) < -pad or min(xs) > w + pad or max(ys) < -pad or min(ys) > h + pad:
            continue
        if max(xs) - min(xs) < 3 and max(ys) - min(ys) < 3:
            continue
        kept = [pts[0]]
        for p in pts[1:]:
            if abs(p[0] - kept[-1][0]) + abs(p[1] - kept[-1][1]) >= min_px:
                kept.append(p)
        if len(kept) > 2:
            out.append("M" + "L".join(f"{x:.1f},{y:.1f}" for x, y in kept) + "Z")
    return "".join(out)


def main(ne_path):
    twc = os.environ["TWC_API_KEY"]
    heads = get_json(f"https://api.weather.com/v3/alerts/headlines?geocode={GEOCODE}"
                     f"&format=json&language=en-CA&apiKey={twc}")
    alert = next(a for a in heads["alerts"] if a["areaName"] == "Labrador City and Wabush")
    detail = get_json(f"https://api.weather.com/v3/alerts/detail?alertId={alert['detailKey']}"
                      f"&format=json&language=en-CA&apiKey={twc}")["alertDetail"]
    poly = [[round(p["lon"], 3), round(p["lat"], 3)] for p in detail["polygon"]]

    feature = {"type": "Feature",
               "properties": {"stroke": "#3f4a4f", "stroke-width": 5,
                              "fill": "#6b777c", "fill-opacity": 0.4},
               "geometry": {"type": "Polygon", "coordinates": [poly]}}
    overlay = "geojson(" + urllib.parse.quote(json.dumps(feature, separators=(",", ":"))) + ")"
    url = (f"https://api.mapbox.com/styles/v1/mapbox/light-v11/static/{overlay}/"
           f"{LON0},{LAT0},{ZOOM},0/{W}x{H}@2x?attribution=false&logo=false"
           f"&access_token={os.environ['MAPBOX_ACCESS_TOKEN']}")
    urllib.request.urlretrieve(url, os.path.join(HERE, "map.png"))

    with open(ne_path) as f:
        provs = {ft["properties"]["name"]: ft["geometry"] for ft in json.load(f)["features"]
                 if ft["properties"].get("adm0_a3") == "CAN"}

    main_proj = projector(LON0, LAT0, ZOOM, W, H)
    ins_proj = projector(INSET["lon0"], INSET["lat0"], INSET["zoom"], INSET["w"], INSET["h"])
    alert_geom = {"type": "Polygon", "coordinates": [poly]}

    data = {
        "alert": {k: alert[k] for k in ("eventDescription", "issueTimeLocal", "endTimeLocal")},
        "main": {
            "nl": path(provs["Newfoundland and Labrador"], main_proj, W, H),
            "towns": {n: [round(v) for v in main_proj(*ll)] for n, ll in TOWNS.items()},
        },
        "inset": {
            "nl": path(provs["Newfoundland and Labrador"], ins_proj, INSET["w"], INSET["h"], 0.8, 40),
            "qc": path(provs["Québec"], ins_proj, INSET["w"], INSET["h"], 0.8, 40),
            "alert": path(alert_geom, ins_proj, INSET["w"], INSET["h"], 0.3, 40),
            # map frame footprint, so the inset shows what the main map covers
            "frame": [round(v, 1) for v in (*ins_proj(*_corner(1)), *ins_proj(*_corner(-1)))],
        },
    }
    with open(os.path.join(HERE, "overlay.js"), "w") as f:
        f.write("// generated by build.py\nwindow.OVERLAY = " + json.dumps(data) + ";\n")


def _corner(sign):
    """Lat/lon of the main map's top-left (sign=1) or bottom-right (sign=-1) corner."""
    s = 512 * 2 ** ZOOM / (2 * math.pi)
    my0 = s * math.log(math.tan(math.pi / 4 + math.radians(LAT0) / 2))
    lon = LON0 - sign * math.degrees((W / 2) / s)
    lat = math.degrees(2 * math.atan(math.exp((my0 + sign * H / 2) / s)) - math.pi / 2)
    return lat, lon


if __name__ == "__main__":
    main(sys.argv[1])
