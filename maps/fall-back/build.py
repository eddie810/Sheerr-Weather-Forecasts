"""Sunrise/sunset before and after clocks fall back (Sun Nov 1, 2026) for NL towns. Writes data.js (window.FB).
Island and southeastern Labrador are on Newfoundland time (NDT -2:30 -> NST -3:30); the rest of Labrador on Atlantic
time (ADT -3 -> AST -4).   python3 build.py   (needs astral)"""
import json
import os
from datetime import date, timedelta, timezone

from astral import LocationInfo
from astral.sun import sun

HERE = os.path.dirname(os.path.abspath(__file__))
TOWNS = {"St. John's": (47.561, -52.713, "NT"), "Gander": (48.954, -54.609, "NT"), "Corner Brook": (48.951, -57.952, "NT"),
         "Burgeo": (47.617, -57.621, "NT"), "St. Anthony": (51.364, -55.580, "NT"), "Nain": (56.542, -61.692, "AT"),
         "Goose Bay": (53.302, -60.417, "AT"), "Labrador City": (52.946, -66.911, "AT")}
OFF = {("NT", 0): -2.5, ("NT", 1): -3.5, ("AT", 0): -3, ("AT", 1): -4}
DAYS = (date(2026, 10, 31), date(2026, 11, 1))


def main():
    out = []
    for n, (la, lo, z) in TOWNS.items():
        row = {"name": n, "zone": z}
        for k, d in enumerate(DAYS):
            s = sun(LocationInfo(n, "", "UTC", la, lo).observer, date=d, tzinfo=timezone.utc)
            tz = timezone(timedelta(hours=OFF[(z, k)]))
            rise, set_ = s["sunrise"].astimezone(tz), s["sunset"].astimezone(tz)
            row["sat" if k == 0 else "sun"] = [rise.hour + rise.minute / 60, set_.hour + set_.minute / 60]
        out.append(row)
    with open(os.path.join(HERE, "data.js"), "w") as f:
        f.write("// generated by build.py\nwindow.FB = " + json.dumps(out) + ";\n")
    print(json.dumps(out, indent=0)[:600])


if __name__ == "__main__":
    main()
