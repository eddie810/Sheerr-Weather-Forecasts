"""Atlantic Canada two-day outlook (e.g. Thanksgiving Sunday + Monday).

TWC daily forecasts for one main community per area; Mapbox basemap; province outlines.

  MAPBOX_ACCESS_TOKEN=... TWC_API_KEY=... python3 build.py ne_10m_admin_1_states_provinces.geojson [first_day_offset]
"""
import json
import math
import os
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
W, H = 1080, 900
LON0, LAT0, ZOOM = -59.7, 48.55, 5.12
# name: (lat, lon, card dx, card dy) - card offset from the town dot, set by hand so cards never overlap
TOWNS = {
    "Goose Bay": (53.30, -60.42, 140, 40), "Corner Brook": (48.95, -57.95, -60, -110), "Gander": (48.95, -54.61, 60, -110),
    "St. John's": (47.56, -52.71, 20, 110), "Bathurst": (47.62, -65.65, 0, -105), "Moncton": (46.09, -64.78, -125, -15),
    "Saint John": (45.27, -66.06, -20, 95), "Charlottetown": (46.24, -63.13, 60, -130), "Sydney": (46.14, -60.19, 150, -30),
    "Halifax": (44.65, -63.57, 150, 40),
}
ICONS = {}
for codes, name in [((32, 34, 36, 31, 33), "sun"), ((30, 29), "partly"), ((28, 27), "mostly"), ((26, 44), "cloud"),
                    ((39, 45), "showers"), ((9, 11, 12, 40), "rain"), ((23, 24, 25), "wind"),
                    ((5, 6, 7, 8, 10, 17, 18, 35), "mix"), ((13, 14, 15, 16, 41, 42, 43, 46), "snow"),
                    ((3, 4, 37, 38, 47), "thunder"), ((19, 20, 21, 22), "fog")]:
    for c in codes:
        ICONS[c] = name


def get(url):
    with urllib.request.urlopen(url, timeout=60) as r:
        return r.read()


def px(lat, lon):
    s = 512 * 2 ** ZOOM
    f = lambda la, lo: ((lo + 180) / 360 * s, (1 - math.log(math.tan(math.pi / 4 + math.radians(la) / 2)) / math.pi) / 2 * s)
    (x, y), (cx, cy) = f(lat, lon), f(LAT0, LON0)
    return [round(x - cx + W / 2, 1), round(y - cy + H / 2, 1)]


def outlines(ne_path):
    names = ("Newfoundland and Labrador", "Québec", "Nova Scotia", "New Brunswick", "Prince Edward Island", "Maine")
    with open(ne_path) as f:
        feats = [ft for ft in json.load(f)["features"] if ft["properties"].get("name") in names]
    out = []
    for ft in feats:
        g = ft["geometry"]
        for poly in (g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]):
            if len(poly[0]) < 15:
                continue
            pts = [px(la, lo) for lo, la in poly[0]]
            kept = [pts[0]] + [p for a, p in zip(pts, pts[1:]) if abs(p[0] - a[0]) + abs(p[1] - a[1]) >= 1]
            out.append("M" + "L".join(f"{x},{y}" for x, y in kept) + "Z")
    return "".join(out)


def main(ne_path, first="1"):
    first = int(first)
    geos = ";".join(f"{t[0]},{t[1]}" for t in TOWNS.values())
    rows = json.loads(get(f"https://api.weather.com/v3/aggcommon/v3-wx-forecast-daily-5day?geocodes={geos}"
                          f"&format=json&units=m&language=en-CA&apiKey={os.environ['TWC_API_KEY']}"))
    towns, days = {}, []
    for (name, t), row in zip(TOWNS.items(), rows):
        d = row["v3-wx-forecast-daily-5day"]
        dp = d["daypart"][0]
        fc = []
        for day in (first, first + 1):
            i = day * 2
            fc.append({"high": d["temperatureMax"][day], "low": d["temperatureMin"][day], "icon": ICONS.get(dp["iconCode"][i], "cloud"),
                       "phrase": dp["wxPhraseLong"][i], "pop": dp["precipChance"][i],
                       "wind": dp["windSpeed"][i], "dir": dp["windDirectionCardinal"][i]})
        days = [d["dayOfWeek"][first], d["dayOfWeek"][first + 1]]
        dates = [d["validTimeLocal"][first][:10], d["validTimeLocal"][first + 1][:10]]
        xy = px(t[0], t[1])
        towns[name] = {"fc": fc, "xy": xy, "card": [round(xy[0] + t[2]), round(xy[1] + t[3])]}
    data = {"days": days, "dates": dates, "towns": towns, "outlines": outlines(ne_path)}
    with open(os.path.join(HERE, "data.js"), "w") as f:
        f.write("// generated by build.py\nwindow.OUT = " + json.dumps(data) + ";\n")
    with open(os.path.join(HERE, "map.png"), "wb") as f:
        f.write(get(f"https://api.mapbox.com/styles/v1/mapbox/light-v11/static/{LON0},{LAT0},{ZOOM},0/{W}x{H}@2x"
                    f"?attribution=false&logo=false&access_token={os.environ['MAPBOX_ACCESS_TOKEN']}"))
    for n, t in towns.items():
        print(f"{n:15s} {t['xy']}  " + "  ".join(f"{f['high']}° {f['icon']} {f['phrase']} {f['pop']}%" for f in t["fc"]))


if __name__ == "__main__":
    main(*sys.argv[1:3])
