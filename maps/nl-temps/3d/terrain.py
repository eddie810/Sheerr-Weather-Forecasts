"""Terrain height grid for the 3D highs scene, on exactly the same Web-Mercator frame as the 2D map
(so the 2D map can be draped on it as a texture). Mapbox Terrain-RGB, 540x480 (half the 1080x960 frame).
Writes 3d/terrain.js: window.TERRAIN = {w, h, km_per_px, data: base64 Int16 metres}.

  MAPBOX_ACCESS_TOKEN=... python3 3d/terrain.py [region]
"""
import base64
import io
import json
import math
import os
import sys
import urllib.error

import numpy as np
from matplotlib.image import imread
from scipy.ndimage import gaussian_filter, map_coordinates

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
import build  # noqa: E402  (nl-temps)


def main(region="island"):
    r = build.REGIONS[region]
    (build.LON0, build.LAT0), build.ZOOM = r["center"], r["zoom"]
    LON, LAT = build.frame_lonlat(0.5)                        # 540 x 480
    tz = 9 if build.ZOOM >= 6.5 else 7                      # Labrador frame is ~16x the area: coarser tiles
    wx = (LON + 180) / 360 * 256 * 2 ** tz
    wy = (1 - np.log(np.tan(np.pi / 4 + np.radians(LAT) / 2)) / np.pi) / 2 * 256 * 2 ** tz
    tx0, ty0, tx1, ty1 = int(wx.min() // 256), int(wy.min() // 256), int(wx.max() // 256), int(wy.max() // 256)
    m = np.zeros(((ty1 - ty0 + 1) * 256, (tx1 - tx0 + 1) * 256))
    tok = os.environ["MAPBOX_ACCESS_TOKEN"]
    for ty in range(ty0, ty1 + 1):
        for tx in range(tx0, tx1 + 1):
            try:
                png = build.fetch(f"https://api.mapbox.com/v4/mapbox.terrain-rgb/{tz}/{tx}/{ty}.pngraw?access_token={tok}")
            except urllib.error.HTTPError:
                continue
            rgb = imread(io.BytesIO(png), format="png")[..., :3] * 255
            m[(ty - ty0) * 256:(ty - ty0 + 1) * 256, (tx - tx0) * 256:(tx - tx0 + 1) * 256] = \
                -10000 + (rgb[..., 0] * 65536 + rgb[..., 1] * 256 + rgb[..., 2]) * 0.1
    z = map_coordinates(m, [wy - ty0 * 256, wx - tx0 * 256], order=1)
    z = gaussian_filter(np.clip(z, 0, None), 1.3)              # soft shoreline: no cliffs for the coast line to smear down
    km_per_px = 40075 * math.cos(math.radians(build.LAT0)) / (512 * 2 ** build.ZOOM) * 2   # per mesh cell (half-res)
    out = {"w": z.shape[1], "h": z.shape[0], "km_per_px": km_per_px,
           "data": base64.b64encode(np.round(z).astype("<i2").tobytes()).decode()}
    with open(os.path.join(HERE, f"terrain{r['suffix']}.js"), "w") as f:
        f.write("// generated by terrain.py\nwindow.TERRAIN = " + json.dumps(out) + ";\n")
    print(z.shape, "max", int(z.max()), "m, km/cell", round(km_per_px, 3))


if __name__ == "__main__":
    main(*sys.argv[1:2])
