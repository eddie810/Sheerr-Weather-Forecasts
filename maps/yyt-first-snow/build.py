"""YYT 'days since snow' graphic: pulls Environment Canada daily climate data for St. John's Intl A
and writes data.js (gap between the last snow and the new one, plus daily highs in between).

  python3 build.py [year]
"""
import csv
import io
import json
import os
import sys
import urllib.request
from datetime import date

HERE = os.path.dirname(os.path.abspath(__file__))
STATION = 50089            # ST. JOHN'S INTL A (climate ID 8403505)


def main(year="2026"):
    url = ("https://climate.weather.gc.ca/climate_data/bulk_data_e.html?format=csv"
           f"&stationID={STATION}&Year={year}&Month=1&Day=1&timeframe=2&submit=Download+Data")
    with urllib.request.urlopen(url, timeout=90) as r:
        rows = list(csv.DictReader(io.StringIO(r.read().decode("utf-8-sig"))))
    snow_days = [r for r in rows if r["Total Snow Flag"] == "T" or (r["Total Snow (cm)"] and float(r["Total Snow (cm)"]) > 0)]
    # newest snow day, and the snow day before it after a gap (spring's last vs fall's first)
    new = snow_days[-1]
    prev = max((r for r in snow_days if r["Date/Time"] < new["Date/Time"] and r["Date/Time"] < f"{year}-08-01"),
               key=lambda r: r["Date/Time"])
    d0, d1 = (date.fromisoformat(prev["Date/Time"]), date.fromisoformat(new["Date/Time"]))
    highs = [[r["Date/Time"], float(r["Max Temp (°C)"])] for r in rows
             if prev["Date/Time"] <= r["Date/Time"] <= new["Date/Time"] and r["Max Temp (°C)"]]
    warm = max(highs, key=lambda h: h[1])
    fmt = lambda r: {"date": r["Date/Time"], "snow": r["Total Snow (cm)"], "flag": r["Total Snow Flag"],
                     "max": r["Max Temp (°C)"], "min": r["Min Temp (°C)"]}
    data = {"days": (d1 - d0).days, "prev": fmt(prev), "new": fmt(new), "highs": highs, "warm": warm}
    with open(os.path.join(HERE, "data.js"), "w") as f:
        f.write("// generated by build.py\nwindow.GAP = " + json.dumps(data) + ";\n")
    print(data["days"], "days", data["prev"], "->", data["new"], "warmest", warm)


if __name__ == "__main__":
    main(*sys.argv[1:2])
